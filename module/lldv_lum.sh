#!/system/bin/sh
# lldv_lum.sh - maxLum selection for the Dolby Vision VSVDB. Source this file, then call:
#
#   lldv_apply_maxlum <vsvdb-hex> <cd/m2>      prints the new VSVDB, or ERR:<reason> (exit status 1)
#   lldv_lum_nearest  <cd/m2>                  prints "<code> <cd/m2 actually selected>", or ERR:<reason>
#
# Rewrites the Target Max PQ field of a VSVDB v2 block to the selectable value nearest to the requested
# luminance.
#
# Target Max PQ is a 5-bit code: byte 7 of the VSVDB (the 0xEB header is byte 0), bits 7:3. The other bits of that
# byte (the Interface field, bits 1:0) are preserved. Code -> PQ12 = 2055 + 65 * code, the same mapping the
# hdmitx21 parser uses (tmaxPQ = byte7 >> 3). The cd/m2 values below are the SMPTE ST 2084 luminance of those PQ
# codes, generated by tools/dv_vsvdb.py (`python3 dv_vsvdb.py table`). Other tools label some codes a few percent
# differently: CoreELEC's decoder calls code 9 "385 cd/m2", this table says 372. The code is what matters.
#
# Whether the Dolby Vision engine (dovi.ko, closed source) uses this field for tone mapping is NOT verified.

# index = Target Max PQ code, value = cd/m2
LLDV_LUM_NITS="94 110 129 150 175 204 237 276 320 372 431 499 578 670 775 897 1037 1200 1387 1605 1856 2147 2485 2876 3330 3857 4470 5183 6014 6982 8113 9434"

lldv_lum_nearest() {
    _ln=$1
    case "$_ln" in
        "" | *[!0-9]*) echo "ERR:MAXLUM must be a whole number of cd/m2, got '$_ln'"; return 1 ;;
    esac
    if [ "${#_ln}" -gt 6 ]; then
        echo "ERR:MAXLUM too large"
        return 1
    fi
    # strip leading zeros so the shell does not read the number as octal
    while [ "${_ln#0}" != "$_ln" ]; do
        _ln=${_ln#0}
    done
    [ -n "$_ln" ] || _ln=0

    _best=0
    _bestn=0
    _bestd=99999999
    _code=0
    for _x in $LLDV_LUM_NITS; do
        _d=$((_x - _ln))
        [ $_d -lt 0 ] && _d=$((0 - _d))
        if [ $_d -lt $_bestd ]; then
            _bestd=$_d
            _best=$_code
            _bestn=$_x
        fi
        _code=$((_code + 1))
    done
    echo "$_best $_bestn"
}

lldv_apply_maxlum() {
    _lv=$1
    case "$_lv" in
        *[!0-9a-f]*) echo "ERR:vsvdb is not lowercase hex"; return 1 ;;
    esac
    if [ "${#_lv}" -lt 24 ] || [ "${_lv:2:8}" != "0146d000" ]; then
        echo "ERR:not a Dolby VSVDB"
        return 1
    fi
    _b5=$((0x${_lv:10:2}))
    if [ $((_b5 >> 5)) -ne 2 ]; then
        echo "ERR:MAXLUM is only supported for VSVDB version 2"
        return 1
    fi

    _r=$(lldv_lum_nearest "$2")
    case "$_r" in
        ERR:*) echo "$_r"; return 1 ;;
    esac
    _best=${_r%% *}

    _b7=$((0x${_lv:14:2}))
    _nb7=$(( (_best << 3) | (_b7 & 7) ))
    printf '%s%02x%s\n' "${_lv:0:14}" $_nb7 "${_lv:16}"
}
